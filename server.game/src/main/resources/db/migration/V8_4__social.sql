-- r3-social: friends, blocks, guilds, trade history and market fees.
-- Everything is keyed by character id; names are looked up from characters.name.

CREATE TABLE friends (
  character_id BIGINT    NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  friend_id    BIGINT    NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  created_at   TIMESTAMP NOT NULL,
  PRIMARY KEY (character_id, friend_id)
);
CREATE INDEX idx_friends_friend ON friends (friend_id);

CREATE TABLE blocked_players (
  character_id BIGINT    NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  blocked_id   BIGINT    NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  created_at   TIMESTAMP NOT NULL,
  PRIMARY KEY (character_id, blocked_id)
);

CREATE TABLE guilds (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Unique case-insensitively; the service stores the lower-cased name in name_key.
  name       VARCHAR(24)  NOT NULL,
  name_key   VARCHAR(24)  NOT NULL UNIQUE,
  tag        VARCHAR(5)   NOT NULL,
  motd       VARCHAR(200) NOT NULL DEFAULT '',
  created_at TIMESTAMP    NOT NULL
);

-- One guild per character, so the character is the key.
CREATE TABLE guild_members (
  character_id BIGINT    NOT NULL PRIMARY KEY REFERENCES characters (id) ON DELETE CASCADE,
  guild_id     BIGINT    NOT NULL REFERENCES guilds (id) ON DELETE CASCADE,
  -- GuildRank ordinal: 0 GRUNT .. 5 BOSS. Exactly one BOSS (the leader) per guild.
  guild_rank   SMALLINT  NOT NULL,
  joined_at    TIMESTAMP NOT NULL
);
CREATE INDEX idx_guild_members_guild ON guild_members (guild_id);

CREATE TABLE guild_log (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id   BIGINT       NOT NULL REFERENCES guilds (id) ON DELETE CASCADE,
  created_at TIMESTAMP    NOT NULL,
  text       VARCHAR(200) NOT NULL
);
CREATE INDEX idx_guild_log_guild ON guild_log (guild_id, id);

-- One row per completed trade; gave_* are human readable summaries of each side's offer.
CREATE TABLE trade_history (
  id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  TIMESTAMP    NOT NULL,
  character_a BIGINT       NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  character_b BIGINT       NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  gave_a      VARCHAR(400) NOT NULL,
  gave_b      VARCHAR(400) NOT NULL
);
CREATE INDEX idx_trade_history_a ON trade_history (character_a, id);
CREATE INDEX idx_trade_history_b ON trade_history (character_b, id);

-- The listing fee the seller paid when listing (not refunded on cancel or expiry).
ALTER TABLE market_listings ADD COLUMN fee INT NOT NULL DEFAULT 0;
CREATE INDEX idx_market_listings_sold ON market_listings (status, kind, dex_id, item_id, sold_at);
