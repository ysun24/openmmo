-- Global market (GTL style). Listed goods sit in escrow until the listing is sold, cancelled or
-- expires:
--   POKEMON  the pokemon row stays owned by the seller but moves to container 'GTS', which the
--            character loader skips, so it cannot be used, traded or listed again.
--   ITEM     the quantity is taken out of character_items and is only held by this row.
-- On a sale the price is credited straight to the seller's characters.money, online or not.

CREATE TABLE market_listings (
  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id   BIGINT      NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
  -- MarketKind enum name: POKEMON or ITEM.
  kind        VARCHAR(8)  NOT NULL,
  pokemon_id  BIGINT      REFERENCES pokemon (id) ON DELETE SET NULL,
  -- Denormalised search keys: the species for a pokemon, the item id for an item.
  dex_id      INT,
  item_id     INT,
  quantity    INT         NOT NULL,
  price       INT         NOT NULL,
  created_at  TIMESTAMP   NOT NULL,
  expires_at  TIMESTAMP   NOT NULL,
  -- MarketStatus enum name: ACTIVE, SOLD, CANCELLED or EXPIRED.
  status      VARCHAR(16) NOT NULL,
  buyer_id    BIGINT      REFERENCES characters (id) ON DELETE SET NULL,
  sold_at     TIMESTAMP,
  closed_at   TIMESTAMP
);

CREATE INDEX idx_market_listings_browse ON market_listings (status, kind, price);
CREATE INDEX idx_market_listings_seller ON market_listings (seller_id, status);
CREATE INDEX idx_market_listings_expiry ON market_listings (status, expires_at);
