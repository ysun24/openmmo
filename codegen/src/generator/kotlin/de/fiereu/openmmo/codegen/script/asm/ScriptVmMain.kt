/**
 * Builds the script interpreter's data for each GBA region: the decomp's event scripts assembled to
 * their real bytecode plus the tables the interpreter reads by name (labels, texts, the command and
 * special tables, flags, vars, species, items, multichoice menus, std strings).
 *
 * Args: `<resources-out> <dialog-dir> <region|decompDir>...`. Writes
 * `<resources-out>/scriptvm/<region>.bin` (gzipped, read by server.game's ScriptImage) and refreshes
 * `<dialog-dir>/<region>.script.json`, the decomp text of every script line the ROM-resolved
 * dialog tables have no id for (synthetic ids, committed so the clients can show them).
 */
fun main(args: Array<String>) {
  val out = File(args[0], "scriptvm").apply { mkdirs() }
  val dialogDir = File(args[1])
  for (spec in args.drop(2)) {
    val (region, path) = spec.split("|")
    val decomp = File(path)
    val t0 = System.currentTimeMillis()
    val result = AsmProbe.assemble(decomp, decomp.name.contains("firered"))
    check(result.errors.isEmpty()) { "[scriptvm] $region: ${result.errors.take(20)}" }
    val tables = DecompTables(decomp, result.resolver)
    val textIds = assignTextIds(region, dialogDir, result)
    write(File(out, "$region.bin"), region, result, tables, textIds)
    println(
        "[scriptvm] $region: ${result.bytes.size} bytes, ${result.labels.size} labels, " +
            "${result.texts.size} texts in ${System.currentTimeMillis() - t0} ms")
  }
}

private val json = Json {
  prettyPrint = true
  prettyPrintIndent = "  "
}

/** Text address -> (dialog id, label). Labels the ROM tables lack get synthetic ids. */
private fun assignTextIds(
    region: String,
    dialogDir: File,
    result: ScriptAssembler.Result
): Map<Int, Pair<Int, String>> {
  val known = HashMap<String, Int>()
  for (name in listOf("$region.json", "$region.extra.json")) {
    val f = File(dialogDir, name)
    if (!f.isFile) continue
    for (l in Json.parseToJsonElement(f.readText()).jsonObject.getValue("lines").jsonArray) {
      val o = l.jsonObject
      known.putIfAbsent(o.getValue("label").jsonPrimitive.content, o.getValue("id").jsonPrimitive.int)
    }
  }
  val labelsAt = HashMap<Int, MutableList<String>>()
  for ((name, addr) in result.labels) labelsAt.getOrPut(addr) { mutableListOf() } += name
  val prefix = if (region == "hoenn") 0x1E000000 else 0x0E000000
  val out = LinkedHashMap<Int, Pair<Int, String>>()
  val synthetic = ArrayList<Triple<String, Int, String>>()
  var n = 0
  for ((addr, text) in result.texts) {
    val names = labelsAt[addr].orEmpty()
    val hit = names.firstOrNull { it in known }
    if (hit != null) {
      out[addr] = known.getValue(hit) to hit
      continue
    }
    // Unlabelled runs are continuations nobody points at.
    val label = names.firstOrNull() ?: continue
    n++
    val id = prefix or n
    out[addr] = id to label
    synthetic += Triple(label, id, text.content.toString())
  }
  // The interpreter's dynamic line: C strings and gStringVar4 text, sent as {STR_VAR_9}.
  synthetic += Triple("OpenMMO_Text_Dynamic", prefix or 0xFFFFFF, "{STR_VAR_9}$")
  val doc = buildJsonObject {
    put("region", region)
    put(
        "note",
        "Generated by :codegen:generateScriptVm. Script text lines (data/maps, data/scripts, " +
            "data/text) the ROM-resolved table has no offset for. Synthetic ids: " +
            "0x${prefix.toString(16)} | n, outside every ROM offset.")
    put(
        "lines",
        buildJsonArray {
          for ((label, id, text) in synthetic) add(
              buildJsonObject {
                put("label", label)
                put("id", id)
                put("text", text)
              })
        })
  }
  val file = File(dialogDir, "$region.script.json")
  val rendered = json.encodeToString(JsonObject.serializer(), doc) + "\n"
  if (!file.isFile || file.readText() != rendered) file.writeText(rendered)
  return out
}

private fun write(
    file: File,
    region: String,
    r: ScriptAssembler.Result,
    t: DecompTables,
    textIds: Map<Int, Pair<Int, String>>,
) {
  DataOutputStream(GZIPOutputStream(file.outputStream().buffered())).use { o ->
    o.writeInt(MAGIC)
    o.writeInt(VERSION)
    o.writeUTF(region)
    o.writeInt(ScriptAssembler.BASE)
    o.writeInt(r.bytes.size)
    o.write(r.bytes)
    o.writeInt(r.labels.size)
    for ((name, addr) in r.labels) {
      o.writeUTF(name)
      o.writeInt(addr)
    }
    o.writeInt(r.texts.size)
    for ((addr, text) in r.texts) {
      val (id, label) = textIds[addr] ?: (0 to "")
      o.writeInt(addr)
      o.writeInt(id)
      o.writeUTF(label)
      o.writeBoolean(text.braille)
      writeLong(o, text.content.toString())
    }
    o.writeInt(r.externs.size)
    for ((addr, name) in r.externs) {
      o.writeInt(addr)
      o.writeUTF(name)
    }
    writeTable(o, table(r, "gScriptCmdTable").map { it.removePrefix("ScrCmd_") })
    writeTable(o, table(r, "gSpecials"))
    writeIdNames(o, t.flags)
    writeIdNames(o, t.vars)
    o.writeInt(t.constants.size)
    for ((name, v) in t.constants) {
      o.writeUTF(name)
      o.writeLong(v)
    }
    o.writeInt(t.species.size)
    for ((id, dex) in t.species) {
      o.writeShort(id)
      o.writeShort(dex)
    }
    o.writeInt(t.menus.size)
    for ((id, items) in t.menus) {
      o.writeShort(id)
      writeTable(o, items)
    }
    writeTable(o, t.stdStrings)
    o.writeInt(t.cStrings.size)
    for ((name, text) in t.cStrings) {
      o.writeUTF(name)
      writeLong(o, text)
    }
    o.writeInt(t.stringTables.size)
    for ((name, rows) in t.stringTables) {
      o.writeUTF(name)
      o.writeInt(rows.size)
      for ((row, items) in rows) {
        o.writeInt(row)
        writeTable(o, items)
      }
    }
  }
}

/** The extern names of a table of words (gScriptCmdTable, gSpecials) up to the next label. */
private fun table(r: ScriptAssembler.Result, label: String): List<String> {
  val start = r.labels[label] ?: error("no $label")
  val end = r.labels.values.filter { it > start }.minOrNull() ?: (start + 4 * 1024)
  return (start until end step 4).map { r.externs[it] ?: "" }.dropLastWhile { it.isEmpty() }
}

private fun writeTable(o: DataOutputStream, names: List<String>) {
  o.writeInt(names.size)
  names.forEach { writeLong(o, it) }
}

private fun writeIdNames(o: DataOutputStream, m: Map<Long, List<String>>) {
  o.writeInt(m.size)
  for ((id, names) in m) {
    o.writeLong(id)
    o.writeShort(names.size)
    names.forEach { o.writeUTF(it) }
  }
}

/** writeUTF caps at 64 KiB; texts and menu labels never come close but be safe. */
private fun writeLong(o: DataOutputStream, s: String) {
  val b = s.toByteArray(Charsets.UTF_8)
  o.writeInt(b.size)
  o.write(b)
}

const val MAGIC = 0x4F4D5356 // "OMSV"
const val VERSION = 1

/** The C side tables the scripts index into, read from the decomp headers and sources. */
class DecompTables(private val decomp: File, private val r: Resolver) {
  private fun defines(rel: String, prefix: String): List<Pair<String, String>> {
    val f = File(decomp, rel)
    if (!f.isFile) return emptyList()
    return Regex("""^#define\s+($prefix\w+)\s+(.+?)\s*(?://.*)?$""", RegexOption.MULTILINE)
        .findAll(f.readText())
        .map { it.groupValues[1] to it.groupValues[2] }
        .toList()
  }

  private fun value(name: String): Long? = (r.resolve(name) as? Num)?.v

  private fun idNames(names: List<String>): Map<Long, List<String>> {
    val out = LinkedHashMap<Long, MutableList<String>>()
    for (n in names) {
      val v = value(n) ?: continue
      out.getOrPut(v) { mutableListOf() } += n
    }
    return out
  }

  val flags: Map<Long, List<String>> =
      idNames(defines("include/constants/flags.h", "FLAG_").map { it.first })

  val vars: Map<Long, List<String>> =
      idNames(defines("include/constants/vars.h", "VAR_").map { it.first })

  /**
   * Named constants the interpreter maps back to names: songs, items, species, trainers, maps,
   * movement actions, object graphics, and the script engine's own ranges.
   */
  val constants: Map<String, Long> by lazy {
    val names = ArrayList<String>()
    for ((file, prefix) in
        listOf(
            "include/constants/songs.h" to "(?:SE_|MUS_)",
            "include/constants/items.h" to "ITEM_",
            "include/constants/species.h" to "SPECIES_",
            "include/constants/moves.h" to "MOVE_",
            "include/constants/event_object_movement.h" to "(?:MOVEMENT_ACTION_|MOVEMENT_TYPE_)",
            "include/constants/event_objects.h" to "OBJ_EVENT_GFX_",
            "include/constants/flags.h" to
                "(?:TEMP_FLAGS_|TRAINER_FLAGS_|SYS_FLAGS|SPECIAL_FLAGS_|DAILY_FLAGS_|FLAG_HIDDEN_ITEMS_START)",
            "include/constants/vars.h" to "(?:VARS_|SPECIAL_VARS_|TEMP_VARS_)",
            "include/constants/decorations.h" to "DECOR_",
            "include/constants/weather.h" to "WEATHER_",
            "include/constants/trade.h" to "INGAME_TRADE_",
            "include/constants/script_menu.h" to "(?:MULTI_|SCROLL_MULTI_|DEPT_STORE_FLOORNUM_)",
            "include/constants/menu.h" to "LISTMENU_",
            "include/constants/field_specials.h" to "(?:ELEVATOR_|SCROLL_MULTI_|DEPT_STORE_)",
            "include/constants/battle_frontier.h" to "SPECIAL_BATTLE_",
            "include/constants/pokemon.h" to "(?:TYPE_|EGG_GROUP_)",
        )) names += defines(file, prefix).map { it.first }
    // Every map, and the trainers by id.
    names += GeneratedConstants.all(decomp).keys.filter { it.startsWith("MAP_") }
    val trainers =
        listOf("include/constants/opponents.h", "include/constants/trainers.h").flatMap {
          defines(it, "TRAINER_")
        }
    names += trainers.map { it.first }.filter { !it.startsWith("TRAINER_CLASS") && !it.startsWith("TRAINER_PIC") }
    val out = LinkedHashMap<String, Long>()
    for (n in names.distinct()) out[n] = value(n) ?: continue
    // setrespawn's heal locations -> their map (src/data/heal_locations.json, 1-based).
    val heal = File(decomp, "src/data/heal_locations.json")
    if (heal.isFile) {
      val arr = Json.parseToJsonElement(heal.readText()).jsonObject.values.first().jsonArray
      for ((i, l) in arr.withIndex()) {
        val map = l.jsonObject["map"]?.jsonPrimitive?.content ?: continue
        value(map)?.let { out["OPENMMO_HEAL_${i + 1}"] = it }
      }
    }
    for (n in listOf("TRAINER_FLAGS_START", "VARS_START", "VARS_END", "SPECIAL_VARS_START",
        "SPECIAL_FLAGS_START", "MOVEMENT_ACTION_STEP_END", "VAR_TEXT_COLOR", "ITEM_SILPH_SCOPE",
        "TRAINER_STEVEN", "SPECIAL_BATTLE_STEVEN", "SPECIES_NONE", "NUM_SPECIES")) value(n)?.let { out[n] = it }
    out
  }

  /** Internal species id -> national dex number. */
  val species: Map<Int, Int> by lazy {
    val dex = HashMap<String, Int>()
    val pokedex = File(decomp, "include/constants/pokedex.h").readText()
    val nat = pokedex.substringAfter("enum {").substringBefore("};")
    Regex("""\bNATIONAL_DEX_(\w+)""").findAll(nat).map { it.groupValues[1] }.distinct().forEachIndexed { i, n ->
      dex[n] = i
    }
    val out = LinkedHashMap<Int, Int>()
    for ((name, _) in defines("include/constants/species.h", "SPECIES_")) {
      val id = value(name)?.toInt() ?: continue
      val d = dex[name.removePrefix("SPECIES_")] ?: continue
      out.putIfAbsent(id, d)
    }
    out
  }

  /** `const u8 gText_X[] = _("...");` across the C sources. */
  val cStrings: Map<String, String> by lazy {
    val out = LinkedHashMap<String, String>()
    val re =
        Regex(
            """const u8 (\w+)\[\]\s*=\s*_\(((?:\s*"(?:[^"\\]|\\.)*")+)\s*\)""")
    File(decomp, "src").walkTopDown().filter { it.isFile && (it.extension == "c" || it.extension == "h") }.forEach { f ->
      val text = f.readText()
      if (!text.contains("_(\"")) return@forEach
      for (m in re.findAll(text)) {
        out.putIfAbsent(
            m.groupValues[1],
            Regex(""""((?:[^"\\]|\\.)*)"""").findAll(m.groupValues[2]).joinToString("") { it.groupValues[1] })
      }
    }
    out
  }

  private val menuArrays: Map<String, List<String>> by lazy {
    val out = HashMap<String, List<String>>()
    val re = Regex("""struct MenuAction (\w+)\[\]\s*=\s*\{(.*?)\};""", RegexOption.DOT_MATCHES_ALL)
    for (f in listOf("src/data/script_menu.h", "src/script_menu.c")) {
      val file = File(decomp, f)
      if (!file.isFile) continue
      for (m in re.findAll(file.readText())) {
        out[m.groupValues[1]] =
            Regex("""\{\s*(\w+)""").findAll(m.groupValues[2]).map { it.groupValues[1] }.toList()
      }
    }
    out
  }

  /** Multichoice id -> its item texts, in order. */
  val menus: Map<Int, List<String>> by lazy {
    val out = LinkedHashMap<Int, List<String>>()
    for (f in listOf("src/data/script_menu.h", "src/script_menu.c")) {
      val file = File(decomp, f)
      if (!file.isFile) continue
      val body = file.readText().substringAfter("sMultichoiceLists[] =", "").substringBefore("};")
      for (m in Regex("""\[(\w+)\]\s*=\s*MULTICHOICE\((\w+)\)""").findAll(body)) {
        val id = value(m.groupValues[1])?.toInt() ?: continue
        val items = menuArrays[m.groupValues[2]] ?: continue
        out[id] = items.map { cStrings[it] ?: it }
      }
    }
    out
  }

  /**
   * The string pointer tables of field_specials.c (FRLG sListMenuLabels / sFloorNamePointers,
   * Emerald sScrollableMultichoiceOptions / sDeptStoreFloorNames ...): name -> row -> texts. A
   * one-dimensional table is row 0.
   */
  val stringTables: Map<String, Map<Int, List<String>>> by lazy {
    val out = LinkedHashMap<String, Map<Int, List<String>>>()
    val f = File(decomp, "src/field_specials.c")
    if (!f.isFile) return@lazy out
    val text = f.readText()
    val re = Regex("""static const u8 \*const (\w+)\[[^\]]*\](\[[^\]]*\])?\s*=\s*\{(.*?)\n\s*\};""", RegexOption.DOT_MATCHES_ALL)
    for (m in re.findAll(text)) {
      val body = m.groupValues[3]
      val rows = LinkedHashMap<Int, List<String>>()
      if (m.groupValues[2].isEmpty()) {
        rows[0] = Regex("""(?:\[\w+\]\s*=\s*)?(g\w+)""").findAll(body).map { cStrings[it.groupValues[1]] ?: it.groupValues[1] }.toList()
      } else {
        for (row in Regex("""\[(\w+)\]\s*=\s*\{(.*?)\}""", RegexOption.DOT_MATCHES_ALL).findAll(body)) {
          val id = value(row.groupValues[1])?.toInt() ?: continue
          rows[id] = Regex("""\b(g\w+)""").findAll(row.groupValues[2]).map { cStrings[it.groupValues[1]] ?: it.groupValues[1] }.toList()
        }
      }
      out[m.groupValues[1]] = rows
    }
    // In-game trades (src/data/trade.h / ingame_trades.h): row = INGAME_TRADE_* id, texts =
    // nickname, OT name, then the numbers as text: species, requested species, held item, OT id,
    // personality, ivs (6).
    for (rel in listOf("src/data/trade.h", "src/data/ingame_trades.h")) {
      val tf = File(decomp, rel)
      if (!tf.isFile) continue
      val rows = LinkedHashMap<Int, List<String>>()
      val tb = tf.readText()
      for (m in Regex("""\[(INGAME_TRADE_\w+)\]\s*=\s*\{(.*?)\n\s*\}""", RegexOption.DOT_MATCHES_ALL).findAll(tb)) {
        val id = value(m.groupValues[1])?.toInt() ?: continue
        val b = m.groupValues[2]
        fun str(f: String) = Regex("""\.$f\s*=\s*_\("([^"]*)"\)""").find(b)?.groupValues?.get(1).orEmpty()
        fun num(f: String) = Regex("""\.$f\s*=\s*([\w+ ]+)""").find(b)?.groupValues?.get(1)?.trim()?.let { value(it) ?: (r.resolve(it) as? Num)?.v ?: it.toLongOrNull() } ?: 0L
        val ivs = Regex("""\.ivs\s*=\s*\{([^}]*)\}""").find(b)?.groupValues?.get(1)?.split(',')?.map { it.trim() }.orEmpty()
        rows[id] = listOf(str("nickname"), str("otName"), num("species").toString(), num("requestedSpecies").toString(),
            num("heldItem").toString(), num("otId").toString(), num("personality").toString()) + ivs
      }
      out["sIngameTrades"] = rows
    }
    out
  }

  /** gStdStrings (bufferstdstring), by index. */
  val stdStrings: List<String> by lazy {
    val sources = listOf("src/data/script_menu.h", "src/scrcmd.c", "src/strings.c", "src/data/strings.h")
    for (f in sources) {
      val file = File(decomp, f)
      if (!file.isFile) continue
      val text = file.readText()
      if (!text.contains("gStdStrings[]")) continue
      val body = text.substringAfter("gStdStrings[]").substringAfter("{").substringBefore("};")
      val out = ArrayList<String>()
      for (m in Regex("""(?:\[(\w+)\]\s*=\s*)?(\w+)\s*,""").findAll("$body,")) {
        val idx = m.groups[1]?.value?.let { value(it)?.toInt() } ?: out.size
        while (out.size <= idx) out += ""
        out[idx] = cStrings[m.groupValues[2]] ?: m.groupValues[2]
      }
      return@lazy out
    }
    emptyList()
  }

}
