package de.fiereu.openmmo.codegen.trainer

import de.fiereu.openmmo.codegen.defineTable
import java.io.File

/**
 * A trainer's rematch parties: [ids] is the first battle's trainer then each rematch tier, -1 for a
 * tier the trainer skips (FRLG `SKIP`). [map] is the decomp map constant.
 */
data class ParsedRematch(val ids: List<Int>, val map: String, val wally: Boolean)

/**
 * Rematch tables: FireRed's VS Seeker `sRematches` (src/vs_seeker.c) and Emerald's Match Call
 * `gRematchTable` (src/battle_setup.c), the latter cut at the gym leaders (special trainers the
 * random rematches skip, REMATCH_SPECIAL_TRAINER_START).
 */
class RematchParser(private val rootDir: File) {
  private val trainerIds = defineTable(File(rootDir, "include/constants/opponents.h"), "TRAINER_")

  fun parseAll(): List<ParsedRematch> {
    val frlg = File(rootDir, "src/vs_seeker.c")
    if (frlg.exists()) return parseFrlg(frlg.readText())
    val emerald = File(rootDir, "src/battle_setup.c")
    if (emerald.exists()) return parseEmerald(emerald.readText())
    return emptyList()
  }

  private fun id(token: String): Int? =
      when (val t = token.trim()) {
        "SKIP" -> -1
        "TRAINER_NONE",
        "0" -> 0
        else -> trainerIds[t]
      }

  private fun parseFrlg(text: String): List<ParsedRematch> {
    val body = text.substringAfter("sRematches[] = {").substringBefore("\n};")
    return FRLG_ENTRY.findAll(body)
        .mapNotNull { m ->
          val ids = m.groupValues[1].split(',').map { id(it) ?: return@mapNotNull null }
          ParsedRematch(ids.takeWhile { it != 0 }, m.groupValues[2], wally = false)
        }
        .toList()
  }

  private fun parseEmerald(text: String): List<ParsedRematch> {
    val body = text.substringAfter("gRematchTable[REMATCH_TABLE_ENTRIES] =").substringBefore("\n};")
    val out = ArrayList<ParsedRematch>()
    for (m in EMERALD_ENTRY.findAll(body)) {
      val name = m.groupValues[1]
      if (name == "REMATCH_ROXANNE") break
      val parts = m.groupValues[2].split(',').map { it.trim() }
      val ids = parts.dropLast(1).map { id(it) ?: return@map 0 }
      out +=
          ParsedRematch(ids.takeWhile { it != 0 }, parts.last(), wally = name == "REMATCH_WALLY_VR")
    }
    return out
  }

  /** Kotlin source of `object <name>` with the table, in [pkg]. */
  fun render(pkg: String, name: String, rows: List<ParsedRematch>): String = buildString {
    append("// Generated by codegen (RematchParser). Do not edit.\n")
    append("package $pkg\n\n")
    append("import de.fiereu.openmmo.trainer.RematchEntry\n\n")
    append("object $name {\n")
    append("  val entries: List<RematchEntry> =\n      listOf(\n")
    for (r in rows) {
      append(
          "          RematchEntry(listOf(${r.ids.joinToString(", ")}), \"${r.map}\", ${r.wally}),\n")
    }
    append("      )\n}\n")
  }

  private companion object {
    val FRLG_ENTRY = Regex("""\{\s*\{([^}]*)}\s*,\s*MAP\((MAP_\w+)\)\s*}""")
    val EMERALD_ENTRY = Regex("""\[(REMATCH_\w+)]\s*=\s*REMATCH\(([^)]*)\)""")
  }
}
