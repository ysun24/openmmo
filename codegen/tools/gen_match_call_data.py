#!/usr/bin/env python3
"""Generates Emerald's Match Call tables (r4) from the pokeemerald decomp into

  codegen/src/main/kotlin/de/fiereu/openmmo/progression/MatchCallTables.kt

* sMatchCallTrainers (src/match_call.c): per trainer the same-route and different-route battle
  request texts and its general (personal) text, as the dialog ids of codegen/dialog/hoenn.json
* the trainers' names (src/data/trainers.h) and their rematch map's MAPSEC name
  (gRematchTable in src/battle_setup.c + the map headers), for {STR_VAR_1} / {STR_VAR_2}

Usage, from the repo root:  python3 codegen/tools/gen_match_call_data.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EM = ROOT / "decomp/pokeemerald"
OUT = ROOT / "codegen/src/main/kotlin/de/fiereu/openmmo/progression/MatchCallTables.kt"


def read(p):
    return (EM / p).read_text(encoding="utf-8")


ids = {l["label"]: l["id"] for l in json.loads((ROOT / "codegen/dialog/hoenn.json").read_text())["lines"]}
opp = {m.group(1): int(m.group(2)) for m in
       re.finditer(r"#define\s+(TRAINER_\w+)\s+(\d+)", read("include/constants/opponents.h"))}

mc = read("src/match_call.c")


def table(name):
    body = mc.split(f"static const struct MatchCallText {name}[] =", 1)[1].split("};", 1)[0]
    return re.findall(r"\.text\s*=\s*(\w+)", body)


topics = {
    "REQ_TOPIC_SAME_ROUTE": table("sMatchCallSameRouteBattleRequestTexts"),
    "REQ_TOPIC_DIFF_ROUTE": table("sMatchCallDifferentRouteBattleRequestTexts"),
    "GEN_TOPIC_PERSONAL": table("sMatchCallPersonalizedTexts"),
}


def text_id(topic, n):
    lst = topics.get(topic)
    if not lst or n < 1 or n > len(lst):
        return 0
    return ids.get(lst[n - 1], 0)


# trainer names
tr = read("src/data/trainers.h")
names = {m.group(1): m.group(2) for m in re.finditer(
    r"\[(TRAINER_\w+)\]\s*=\s*\{.*?\.trainerName\s*=\s*_\(\"([^\"]*)\"\)", tr, re.S)}

# rematch maps -> region map section names
bs = read("src/battle_setup.c")
rem = {}
for m in re.finditer(r"REMATCH\(\s*(TRAINER_\w+)\s*,(?:[^)]*?),\s*(\w+)\s*\)", bs):
    rem[m.group(1)] = m.group(2)
maps = {}
for p in (EM / "data/maps").glob("*/map.json"):
    j = json.loads(p.read_text(encoding="utf-8"))
    maps[j["id"]] = j.get("region_map_section", "")
secnames = {}
rm = read("src/data/region_map/region_map_entries.h") if (EM / "src/data/region_map/region_map_entries.h").exists() else ""
for m in re.finditer(r"\[(MAPSEC_\w+)\]\s*=\s*\{[^}]*?\.name\s*=\s*(\w+)", rm):
    secnames[m.group(1)] = m.group(2)
strings = {m.group(1): m.group(2) for m in re.finditer(r"static const u8 (\w+)\[\]\s*=\s*_\(\"([^\"]*)\"\)", rm)}

rows = []
for m in re.finditer(r"\.trainerId\s*=\s*(TRAINER_\w+),(.*?)\n    \}", mc, re.S):
    t = m.group(1)
    body = m.group(2)
    def tid(field):
        x = re.search(r"\." + field + r"\s*=\s*TEXT_ID\((\w+),\s*(\d+)\)", body)
        return text_id(x.group(1), int(x.group(2))) if x else 0
    sec = maps.get("MAP_" + rem.get(t, "").removeprefix("MAP_"), "") if t in rem else ""
    sec = maps.get(rem.get(t, ""), "")
    secname = strings.get(secnames.get(sec, ""), sec.removeprefix("MAPSEC_").replace("_", " "))
    rows.append((opp.get(t, 0), names.get(t, t), secname, tid("sameRouteMatchCallTextId"),
                 tid("differentRouteMatchCallTextId"), tid("generalTextId"), sec))

s = ";".join(f"{a}/{b}/{c}/{d}/{e}/{f}/{g}" for a, b, c, d, e, f, g in rows)
OUT.write_text(f"""// GENERATED by codegen/tools/gen_match_call_data.py from the pokeemerald decomp. Do not edit.
package de.fiereu.openmmo.progression

/** sMatchCallTrainers: `trainerId/NAME/route/sameRouteText/diffRouteText/generalText/MAPSEC;...` */
object MatchCallTables {{
  val TRAINERS =
      "{s}"
}}
""", encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} match call trainers, "
      f"{sum(1 for r in rows if r[3])} with texts, {sum(1 for r in rows if r[2])} with a route")
