#!/usr/bin/env python3
"""Writes codegen/src/main/kotlin/de/fiereu/openmmo/progression/SpeciesWeights.kt from the decomp.

The weights (hectograms) come from pokeemerald's src/data/pokemon/pokedex_entries.h, indexed by the
NATIONAL_DEX_* enum of include/constants/pokedex.h. Low Kick (Cmd_weightdamagecalculation) reads
them. Run from the repository root: python3 codegen/tools/gen_species_weights.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EM = ROOT / "decomp/pokeemerald"
OUT = ROOT / "codegen/src/main/kotlin/de/fiereu/openmmo/progression/SpeciesWeights.kt"


def main():
    enum = (EM / "include/constants/pokedex.h").read_text()
    names = re.findall(r"^\s*(NATIONAL_DEX_\w+),", enum, re.M)
    index = {n: i for i, n in enumerate(names)}
    text = (EM / "src/data/pokemon/pokedex_entries.h").read_text()
    weights = {}
    for m in re.finditer(r"\[(NATIONAL_DEX_\w+)\]\s*=\s*\{(.*?)\n    \}", text, re.S):
        w = re.search(r"\.weight = (\d+)", m.group(2))
        if w and m.group(1) in index:
            weights[index[m.group(1)]] = int(w.group(1))
    top = max(weights)
    values = [weights.get(i, 0) for i in range(top + 1)]
    rows = ",\n".join(
        "          " + ", ".join(str(v) for v in values[i:i + 16]) for i in range(0, len(values), 16))
    OUT.write_text(f"""// Generated by codegen/tools/gen_species_weights.py from pokeemerald pokedex_entries.h. Do not edit.
package de.fiereu.openmmo.progression

/** Species weights in hectograms (0.1 kg), by national dex number (0 is unused). */
object SpeciesWeights {{
  private val WEIGHTS =
      intArrayOf(
{rows})

  /** The weight of national dex [dex] in hectograms, or 0 when unknown. */
  fun hectograms(dex: Int): Int = WEIGHTS.getOrElse(dex) {{ 0 }}
}}
""")
    print(f"wrote {OUT} ({len(values) - 1} species)")


if __name__ == "__main__":
    main()
